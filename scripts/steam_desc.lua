[h1]吞噬者背包[/h1]
[i]🎯 当一个人有自信的时候，别人会放弃他们那游移不定的意见来附和他。 —— 罗兰[/i]

[h2]功能介绍[/h2]
[list]
[*]吞噬物品/食物增强属性或背包功能
[*]背包内物品[b]防偷窃[/b]（火药猴不会偷背包内物品）
[*]猴子/水獭仍需防范
[*]吞噬者并非普通背包的功能升级，而是需要额外制作的特殊背包，请在容器制作栏查看，制作无需科技
[/list]

[quote]操作方式：拖动物品到背包上[b]右键点击吞噬[/b]，不同物品提供不同效果(请不要把背包放到地上吞噬物品，可能会吞噬失败)。
或者拖动背包到特殊不可移动物品上吞噬(需要关闭游戏里面的 设置-高级-延迟补偿 这个选项)
[/quote]

[h3]升级系统[/h3]
[list]
[*]吞噬特定物品可提升背包格子
[*]升级背包，升级后解锁部分效果，初始为1，满级为3
[*]格子随等级变化：
  [olist]
  [*]1级：2×2
  [*]2级：2×3
  [*]3级：3×4
  [/olist]
[*]界限突破：基础防御最大为99%，超过100%的基础防御，每2%会增加其他数值属性的1%
[/list]

[h3]快捷键配置[/h3]
[list]
[*][b]F7[/b]：打开/关闭控制面板（默认快捷键，可在Mod配置页面修改）
[*][b]F8[/b]：切换当前绑定的功能（循环切换功能列表）
[*][b]F9[/b]：执行当前绑定的功能（切换该功能的开关状态）
[/list]
[i]快捷键均可在Mod配置页面修改为其他按键[/i]

[h3]特殊功能物品[/h3]
[list]
[*][b]金块[/b]：显示 升级所需物品 + 随机推荐物品
[*][b]月岩[/b]：显示已吞噬功能
[/list]

可以通过快捷键打开一些特殊功能的配置页面，默认F7，可以在Mod配置页面修改快捷键

